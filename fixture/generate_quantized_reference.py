"""Quantized reference for the official DSA decode configuration.

Every matrix multiply and accumulation is integer.  Only the final
per-head dequantization scalar is floating point.  The softmax becomes a
256-entry UINT8 lookup table, which removes the floating-point exponential
units entirely from the hardware.
"""

import numpy as np
from pathlib import Path

SEED = 20260728
CONTEXT = 4096
INDEX_HEADS, INDEX_DIM, TOPK = 64, 128, 2048
ATTN_HEADS, LATENT_DIM, ROPE_DIM, VALUE_DIM = 16, 512, 64, 128
QK_DIM = LATENT_DIM + ROPE_DIM          # 576
SOFTMAX_DIVISOR = float(np.sqrt(QK_DIM))  # 24.0

# UINT8 softmax table: EXP_LUT[d] = round(255 * exp(-d / 24)).
# Entries beyond d = 149 round to zero, so 256 entries cover the whole
# useful range and the hardware needs one small ROM.
EXP_LUT = np.array(
    [int(round(255.0 * np.exp(-d / SOFTMAX_DIVISOR))) for d in range(256)],
    dtype=np.uint8,
)

rng = np.random.default_rng(SEED)

index_q = rng.integers(-8, 8, (INDEX_HEADS, INDEX_DIM), dtype=np.int8)
index_k = rng.integers(-8, 8, (CONTEXT, INDEX_DIM), dtype=np.int8)
index_weights = rng.integers(-8, 8, (INDEX_HEADS,), dtype=np.int8)

head_dots = index_q.astype(np.int32) @ index_k.astype(np.int32).T
index_scores = (index_weights.astype(np.int64)
                @ np.maximum(head_dots, 0).astype(np.int64))

token_ids = np.arange(CONTEXT, dtype=np.int64)
selected = np.lexsort((token_ids, -index_scores))[:TOPK].astype(np.int32)

q_latent = rng.integers(-128, 128, (ATTN_HEADS, LATENT_DIM),
                        dtype=np.int16).astype(np.int8)
q_rope = rng.integers(-128, 128, (ATTN_HEADS, ROPE_DIM),
                      dtype=np.int16).astype(np.int8)
latent_cache = rng.integers(-128, 128, (CONTEXT, LATENT_DIM),
                            dtype=np.int16).astype(np.int8)
pe_cache = rng.integers(-128, 128, (CONTEXT, ROPE_DIM),
                        dtype=np.int16).astype(np.int8)
value_projection = rng.integers(-8, 8,
                                (ATTN_HEADS, VALUE_DIM, LATENT_DIM),
                                dtype=np.int8)

selected_latent = latent_cache[selected].astype(np.int32)
selected_pe = pe_cache[selected].astype(np.int32)

# ---- step 1: INT8 x INT8 -> INT32 attention scores ----
scores = (q_latent.astype(np.int32) @ selected_latent.T
          + q_rope.astype(np.int32) @ selected_pe.T)
assert np.abs(scores).max() < 2 ** 31

# ---- step 2: table-driven UINT8 softmax ----
distance = np.minimum(scores.max(axis=1, keepdims=True) - scores, 255)
probabilities_u8 = EXP_LUT[distance.astype(np.int64)]

# ---- step 3: UINT32 denominator ----
denominator = probabilities_u8.astype(np.int64).sum(axis=1)

# ---- step 4: UINT8 x INT8 -> INT32 weighted latent ----
weighted_int = (probabilities_u8.astype(np.int64)
                @ selected_latent.astype(np.int64))
assert np.abs(weighted_int).max() < 2 ** 31

# ---- step 5: power-of-two requantization to INT8 ----
magnitude = np.abs(weighted_int).max(axis=1)
shift = np.array(
    [max(0, int(m).bit_length() - 7) for m in magnitude], dtype=np.int32)
weighted_i8 = np.empty((ATTN_HEADS, LATENT_DIM), dtype=np.int8)
for head in range(ATTN_HEADS):
    scaled = weighted_int[head] >> shift[head]      # arithmetic shift
    weighted_i8[head] = np.clip(scaled, -128, 127).astype(np.int8)

# ---- step 6: INT8 x INT8 -> INT32 value projection ----
output_int = np.einsum("hc,hvc->hv",
                       weighted_i8.astype(np.int32),
                       value_projection.astype(np.int32))
assert np.abs(output_int).max() < 2 ** 31

# ---- step 7: per-head dequantization (the only float operation) ----
dequant = (2.0 ** shift) / denominator
output = output_int.astype(np.float64) * dequant[:, None]

out = Path("official_fixture_ctx4096_quant.npz")
np.savez_compressed(
    out,
    exp_lut=EXP_LUT,
    selected=selected,
    attention_scores=scores.astype(np.int32),
    probabilities_u8=probabilities_u8,
    denominator=denominator.astype(np.int64),
    weighted_int=weighted_int.astype(np.int32),
    shift=shift,
    weighted_i8=weighted_i8,
    output_int=output_int.astype(np.int32),
    output=output,
)

binary_dir = Path("official_fixture_ctx4096_bin")
binary_dir.mkdir(exist_ok=True)
output.astype(np.float64).tofile(binary_dir / "output_quant.bin")
output_int.astype(np.int32).tofile(binary_dir / "output_quant_int.bin")

# Emit the LUT as a header so C++ and HLS use byte-identical values.
with open("odsa_exp_lut.hpp", "w") as handle:
    handle.write("#ifndef ODSA_EXP_LUT_HPP\n#define ODSA_EXP_LUT_HPP\n\n")
    handle.write("// Generated by generate_quantized_reference.py.\n")
    handle.write("// ODSA_EXP_LUT[d] = round(255 * exp(-d / sqrt(576))).\n")
    handle.write("static const unsigned char ODSA_EXP_LUT[256] = {\n")
    for row in range(0, 256, 16):
        handle.write("    " + ", ".join(
            "%3d" % int(v) for v in EXP_LUT[row:row + 16]) + ",\n")
    handle.write("};\n\n#endif\n")

print("QUANTIZED REFERENCE PASS")
print("softmax divisor      :", SOFTMAX_DIVISOR)
print("nonzero LUT entries  :", int((EXP_LUT > 0).sum()))
print("score abs max        :", int(np.abs(scores).max()))
print("weighted_int abs max :", int(np.abs(weighted_int).max()))
print("shift per head       :", shift.tolist())
print("denominator range    :", int(denominator.min()), int(denominator.max()))
print("output_int abs max   :", int(np.abs(output_int).max()))
print("output shape         :", output.shape)
print("output checksum      :", float(output.sum()))
print("wrote", out, "and odsa_exp_lut.hpp")
